#!/usr/bin/env python3
"""Generate docs/evaluation/REQUIREMENTS_EVIDENCE_MATRIX.md from .build/requirements.json,
.build/task-graph.json and .build/evidence.jsonl. A requirement is 'covered' only when every
task that lists it is verified; evidence classes are listed separately and never merged."""
import json, os, collections
B = os.path.join(os.path.dirname(__file__), "..")
R = json.load(open(os.path.join(B, "requirements.json")))["requirements"]
T = json.load(open(os.path.join(B, "task-graph.json")))["tasks"]
E = [json.loads(l) for l in open(os.path.join(B, "evidence.jsonl")) if l.strip()]
ev_by_req = collections.defaultdict(list)
for e in E:
    for r in e.get("requirement_ids", []): ev_by_req[r].append(e)
tasks_by_req = collections.defaultdict(list)
for t in T:
    for r in t["requirement_ids"]: tasks_by_req[r].append(t)
out = ["# Requirement-to-evidence matrix", "", "Generated by `.build/tools/matrix.py`. Status is `covered` only when every task listing the requirement is `verified`. Evidence classes are reported as recorded; `automated` never stands in for `real_phone`, `real_VVD` or `physical_Fire_TV`.", "", "| Req | Area | Tasks (status) | Evidence (class) | Coverage |", "|---|---|---|---|---|"]
for r in R:
    ts = tasks_by_req.get(r["id"], [])
    tstr = ", ".join(f'{t["id"]} ({t["status"]})' for t in ts) or "—"
    es = ev_by_req.get(r["id"], [])
    estr = ", ".join(f'{e["id"]} ({e.get("evidence_class")})' for e in es) or "—"
    cov = "covered" if ts and all(t["status"] == "verified" for t in ts) else ("blocked" if any(t["status"] == "blocked_external" for t in ts) else "open")
    out.append(f'| {r["id"]} | {r["area"]} | {tstr} | {estr} | {cov} |')
p = os.path.join(B, "..", "docs", "evaluation", "REQUIREMENTS_EVIDENCE_MATRIX.md")
open(p, "w").write("\n".join(out) + "\n")
c = collections.Counter(l.split("|")[-2].strip() for l in out[6:])
print(dict(c))
